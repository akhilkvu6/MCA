DELIMITER //

CREATE TRIGGER updateAvailabeQuantity

AFTER INSERT
ON Saleitem

FOR EACH ROW

BEGIN

    UPDATE Product

    SET Qtyinstock = Qtyinstock - NEW.Qty

    WHERE PdtId = NEW.PdtId;

END //

DELIMITER ;

